"""Build offline city lookup from DataV GCJ-02 boundaries; never send user GPS.

Run with --fetch once to cache the public inputs. Default builds from that cache.
Source: https://geo.datav.aliyun.com/areas_v3/bound/{adcode}_full.json
Coordinate reference: https://help.aliyun.com/en/datav/datav-7-0/user-guide/map-data-format-1
"""
import base64
import concurrent.futures
import gzip
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'outputs/gps-nearby-2026-11-04/raw-boundaries'
CACHE.mkdir(parents=True, exist_ok=True)

def fetch(code):
    path = CACHE / (str(code) + '_full.json')
    if not path.exists():
        subprocess.run(['curl', '-fsSL', '--retry', '2', '--max-time', '40',
                        f'https://geo.datav.aliyun.com/areas_v3/bound/{code}_full.json',
                        '-o', str(path)], check=True)
    return json.loads(path.read_text())['features']

provinces = fetch(100000)
special = {110000, 120000, 310000, 500000, 710000, 810000, 820000}
codes = [p['properties']['adcode'] for p in provinces if p['properties']['adcode'] not in special and p['properties'].get('name')]
if '--fetch' in sys.argv:
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        list(pool.map(fetch, codes))

def simplify(points, tolerance=.001):
    # Douglas-Peucker, ~100 m tolerance. Keep every island and polygon hole.
    if len(points) < 3:
        return points
    a, b = points[0], points[-1]
    dx, dy = b[0]-a[0], b[1]-a[1]
    norm = dx*dx+dy*dy
    def dist(p):
        t = max(0, min(1, ((p[0]-a[0])*dx+(p[1]-a[1])*dy)/norm)) if norm else 0
        return (p[0]-a[0]-t*dx)**2+(p[1]-a[1]-t*dy)**2
    i = max(range(1, len(points)-1), key=lambda i: dist(points[i]))
    if dist(points[i]) <= tolerance*tolerance:
        return [a, b]
    return simplify(points[:i+1], tolerance)[:-1]+simplify(points[i:], tolerance)

rows = []
for province in provinces:
    pp = province['properties']
    if not pp.get('name'):
        continue
    code = pp['adcode']
    features = [province] if code in special else json.loads((CACHE / f'{code}_full.json').read_text())['features']
    for f in features:
        props, geo = f['properties'], f['geometry']
        if not props.get('name'):
            continue
        polygons = geo['coordinates'] if geo['type'] == 'MultiPolygon' else [geo['coordinates']]
        rings = []
        for polygon in polygons:
            result = []
            for ring in polygon:
                simple = simplify(ring)
                if len(simple) < 4:
                    simple = ring
                result.append([[round(x*10000), round(y*10000)] for x,y in simple])
            rings.append(result)
        pts = [p for poly in rings for ring in poly for p in ring]
        bounds = [min(p[0] for p in pts), min(p[1] for p in pts), max(p[0] for p in pts), max(p[1] for p in pts)]
        # Taiwan's province feed has no city children. Do not label the province a city.
        rows.append([props['adcode'], pp['name'], '' if code == 710000 else props['name'], bounds, rings])

# Zigzag varints store delta coordinates without changing any geometry.
index, payload = [], bytearray()
def integer(value):
    value = value*2 if value >= 0 else -value*2-1
    while value >= 128:
        payload.append((value & 127) | 128)
        value >>= 7
    payload.append(value)
for row in rows:
    index.append(row[:4]+[[[len(ring) for ring in poly] for poly in row[4]]])
    for poly in row[4]:
        for ring in poly:
            previous = [0, 0]
            for point in ring:
                integer(point[0]-previous[0])
                integer(point[1]-previous[1])
                previous = point
header = json.dumps(index, ensure_ascii=False, separators=(',', ':')).encode()
raw = len(header).to_bytes(4, 'little') + header + payload
encoded = base64.b64encode(gzip.compress(raw, mtime=0)).decode()
code = "// Generated by tools/build-location-cities.py; DataV GCJ-02 boundaries, retrieved 2026-11-04.\n"
code += "const inflate=require('../../services/vendor/pako-inflate').inflate;\nconst base64='"+encoded+"';\n"
code += """
const alphabet='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
const bytes=new Uint8Array(Math.floor(base64.length*3/4)-(base64.endsWith('==')?2:base64.endsWith('=')?1:0));
let bits=0,value=0,offset=0;
for(let i=0;i<base64.length;i++){const n=alphabet.indexOf(base64[i]);if(n<0)break;value=(value<<6)|n;bits+=6;if(bits>=8){bits-=8;bytes[offset++]=(value>>>bits)&255;}}
const data=inflate(bytes),size=data[0]+data[1]*256+data[2]*65536+data[3]*16777216;
let escaped='';for(let i=4;i<4+size;i++)escaped+='%'+data[i].toString(16).padStart(2,'0');
const rows=JSON.parse(decodeURIComponent(escaped));offset=4+size;
function integer(){let n=0,shift=0,b;do{b=data[offset++];n+=(b&127)*Math.pow(2,shift);shift+=7;}while(b&128);return n%2?-(n+1)/2:n/2;}
for(const row of rows)row[4]=row[4].map(poly=>poly.map(count=>{let x=0,y=0;const ring=[];for(let i=0;i<count;i++){x+=integer();y+=integer();ring.push([x,y]);}return ring;}));
module.exports=rows;
"""
(ROOT/'qingye-miniprogram/miniprogram/packages/location-data/location-cities-data.js').write_text(code)
print(json.dumps({'areas': len(rows), 'bytes': len(code.encode())}))
