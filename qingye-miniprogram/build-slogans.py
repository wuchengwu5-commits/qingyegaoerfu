"""Build the editable copy catalog into a native module and portable database."""
from pathlib import Path
import csv
import json
import sqlite3

ROOT = Path(__file__).resolve().parent
THEMES = {'relax': '放松', 'heal': '治愈', 'golf': '想去打球', 'move': '热爱运动'}


def build():
    with (ROOT / 'content/slogans.csv').open(encoding='utf-8-sig', newline='') as f:
        records = list(csv.DictReader(f))
    ids, titles = set(), set()
    for row in records:
        assert row['id'] and row['id'] not in ids, '重复或空编号'
        assert row['title'] not in titles, '重复标题：' + row['title']
        assert row['theme'] in THEMES, '未知主题'
        assert 1 <= len(row['title']) <= 16, '标题过长：' + row['title']
        assert 1 <= len(row['subtitle']) <= 34, '小字过长：' + row['subtitle']
        assert row['enabled'] in ('0', '1'), '启用状态应为 0 或 1'
        ids.add(row['id'])
        titles.add(row['title'])
        row['enabled'] = row['enabled'] == '1'
    assert all(any(r['enabled'] and r['theme'] == t for r in records) for t in THEMES)
    catalog = {'schemaVersion': 1, 'themes': THEMES, 'entries': records}
    encoded = json.dumps(catalog, ensure_ascii=False, separators=(',', ':'))
    (ROOT / 'miniprogram/services/slogans-data.js').write_text(
        '// Generated by build-slogans.py; edit content/slogans.csv.\nmodule.exports=' + encoded + ';\n', encoding='utf-8')
    (ROOT / 'content/slogans.json').write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    with sqlite3.connect(ROOT / 'content/slogans.sqlite3') as db:
        db.execute('CREATE TABLE IF NOT EXISTS themes (id TEXT PRIMARY KEY, name TEXT NOT NULL)')
        db.execute('''CREATE TABLE IF NOT EXISTS slogans (
            id TEXT PRIMARY KEY, theme TEXT NOT NULL REFERENCES themes(id),
            title TEXT NOT NULL UNIQUE, subtitle TEXT NOT NULL,
            enabled INTEGER NOT NULL CHECK (enabled IN (0, 1)))''')
        db.execute('DELETE FROM slogans')
        db.execute('DELETE FROM themes')
        db.executemany('INSERT INTO themes VALUES (?, ?)', THEMES.items())
        db.executemany('INSERT INTO slogans VALUES (?, ?, ?, ?, ?)',
                       [(r['id'], r['theme'], r['title'], r['subtitle'], int(r['enabled'])) for r in records])
        db.execute('CREATE INDEX IF NOT EXISTS slogans_theme_enabled ON slogans(theme, enabled)')
    lines = ['# 青野 · 轮换文案库', '', '首批 120 组，每组包含标题和配套小字。', '']
    for theme, label in THEMES.items():
        lines += ['## ' + label, '', '| 编号 | 标题 | 配套小字 |', '|---|---|---|']
        lines += ['| ' + ' | '.join([r['id'], r['title'], r['subtitle']]) + ' |'
                  for r in records if r['theme'] == theme]
        lines.append('')
    (ROOT / 'content/文案总览.md').write_text('\n'.join(lines), encoding='utf-8')
    print(json.dumps({'entries': len(records), 'themes': {THEMES[t]: sum(r['theme'] == t for r in records) for t in THEMES},
                      'native_bytes': len(encoded.encode('utf-8'))}, ensure_ascii=False))


if __name__ == '__main__':
    build()
